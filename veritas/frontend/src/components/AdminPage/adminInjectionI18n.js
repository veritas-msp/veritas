export function getAdminInjectionCopy(locale) {
  const t = getCopy(locale);
  return {
    ...t,
    filesSelectedLabel: count => interpolate(t.filesSelected, {
      count
    }),
    previewTitleLabel: count => interpolate(t.previewTitle, {
      count
    }),
    previewTitleFilteredLabel: (filtered, total) => interpolate(t.previewTitleFiltered, {
      filtered,
      total
    }),
    progressLabel: (current, total) => interpolate(t.progress, {
      current,
      total
    }),
    resultOkLabel: count => interpolate(t.resultOk, {
      count
    }),
    resultUpdatedLabel: count => interpolate(t.resultUpdated, {
      count
    }),
    resultFailedLabel: count => interpolate(t.resultFailed, {
      count
    }),
    resultSkippedLabel: count => interpolate(t.resultSkipped, {
      count
    }),
    docsManageLabel: count => interpolate(t.docsManage, {
      count
    }),
    docsModalSubtitleLabel: (count, ready) => interpolate(t.docsModalSubtitle, {
      count,
      ready
    }),
    errorMessage: (key, params = {}) => interpolate(t.errors?.[key] || key, params),
    lineLabel: line => interpolate(t.errors?.linePrefix || "L{line}", {
      line
    })
  };
}
