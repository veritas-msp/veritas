const getCopy = createLocaleGetter(COPY);

export function getTicketValidationCopy(locale) {
  const t = getCopy(locale);
  return {
    ...t,
    formatBannerForYou: name => interpolate(t.bannerForYou, { name: name || "—" }),
    formatBannerWaiting: name => interpolate(t.bannerWaiting, { name: name || "—" }),
    formatBannerMessage: message => interpolate(t.bannerMessage, { message: message || "" })
  };
}
