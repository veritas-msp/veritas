export function resolveEnterpriseIcon(icon) {
  const trimmed = String(icon || "").trim();
  return trimmed || DEFAULT_ENTERPRISE_ICON;
}

export function resolveEnterpriseIconColor(color) {
  const trimmed = String(color || "").trim();
  if (/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(trimmed)) return trimmed;
  return DEFAULT_ENTERPRISE_ICON_COLOR;
}
